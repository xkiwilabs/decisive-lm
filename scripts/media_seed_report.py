"""Seed spread of the 300-item image and audio examples, and KonIQ photo quality at more image detail
(results/media_seeds_gold_test_300.md; guide 9.9).

    uv run python scripts/media_seed_report.py --out results/media_seeds_gold_test_300.md
    uv run python scripts/media_seed_report.py --general generalv5c --out results/media_seeds_gold_test_300_v5c.md

Needs data/predictions/ex_<set>_<base|general>_n300_seed<s>.jsonl (<general> is --general's tag) from scripts/train_p3.py --n-train 300 --seed <s>
(guide 9.9), and for KonIQ also `_img1120` runs on every seed and `_img560` on seed 0 (--image-budget). Each seed
draws its own 300 training rows and its own initialisation. Every figure is scripts/eval_dataset.py on gold_test
(1,000 paired item-level resamples, seed 0); Δ is general minus base on the same seed, or a detail level minus the
same start at 280 tokens on the same seed.
"""
import argparse
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
PRED = REPO / "data" / "predictions"
SETS = {"crema_d": "voice emotion (audio)", "things_living": "is it alive? (image)",
        "koniq10k": "photo quality (image)"}
SEEDS = (0, 1, 2)
GENERAL = {"general": "general_v3d_e4b_r8_seed0", "generalv5c": "general_v5c_e4b_r8_seed0"}   # file tag -> head


def evaluate(data: str, preds: dict[str, pathlib.Path], reference: str) -> tuple[str, dict[str, dict[str, str]]]:
    """(primary metric, method -> column -> cell) from eval_dataset.py's table for the set's one question."""
    md = subprocess.run([sys.executable, REPO / "scripts" / "eval_dataset.py",
                         "--data", REPO / f"data/processed/{data}.jsonl",
                         "--n-boot", "1000", "--reference", reference,
                         "--predictions", *[f"{k}={v}" for k, v in preds.items()]],
                        cwd=REPO, check=True, capture_output=True, text=True).stdout
    lines = [l for l in md.splitlines() if l.startswith("|")]
    head = [c.strip() for c in lines[0].strip("|").split("|")]
    primary = next(h[:-len(" 95% CI")] for h in head if h.endswith(" 95% CI"))
    rows = {}
    for l in lines[2:]:
        cells = [c.strip() for c in l.strip("|").split("|")]
        rows[cells[0]] = dict(zip(head, cells))
    return primary, rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=pathlib.Path)
    ap.add_argument("--general", default="general", choices=list(GENERAL),
                    help="which general head's runs: their file tag (general = v3d, generalv5c = v5c)")
    a = ap.parse_args()
    head = GENERAL[a.general]
    out = ["# Image and audio examples: seed spread and image detail\n",
           "gold_test of each set. Each example trains on 300 rows: **base** from the plain backbone, **general** from "
           f"the general head ({head}). Seeds 0-2 each draw their own 300 training rows and "
           "initialisation. Generated by `scripts/media_seed_report.py`; 95% CIs from 1,000 paired item-level "
           "resamples.\n"]
    for data, what in SETS.items():
        out.append(f"## {data}: {what}\n")
        table, primary = [], None
        for seed in SEEDS:
            preds = {f"{arm} seed {seed}": PRED / f"ex_{data}_{a.general if arm == 'general' else arm}_n300_seed{seed}.jsonl"
                     for arm in ("base", "general")}
            primary, rows = evaluate(data, preds, f"base seed {seed}")
            for name, r in rows.items():
                d = "—" if r[f"Δ{primary} vs ref"] == "—" else f"{r[f'Δ{primary} vs ref']} {r['95% CI']}"
                table.append(f"| {name} | {r['soft NLL']} | {r[primary]} | {r['ρ(top p, agreement)']} "
                             f"| {r['tie AUROC']} | {d} |")
        out.append(f"| Run | soft NLL | {primary} | ρ(top p, agreement) | tie AUROC | Δ{primary}, general − base "
                   f"[95% CI] |\n|---|---|---|---|---|---|\n" + "\n".join(table) + "\n")
    table = []
    for seed in SEEDS:
        for arm in ("base", "general"):
            detail = {f"{arm} {b} seed {seed}":
                      PRED / f"ex_koniq10k_{a.general if arm == 'general' else arm}_n300_seed{seed}{'' if b == 280 else f'_img{b}'}.jsonl"
                      for b in ((280, 560, 1120) if seed == 0 and (arm == "base" or a.general == "general") else (280, 1120))}
            primary, rows = evaluate("koniq10k", detail, f"{arm} 280 seed {seed}")
            table += [f"| {n} | {r['soft NLL']} | {r[primary]} | {r['ρ(top p, agreement)']} | {r['tie AUROC']} | "
                      + ("—" if r[f"Δ{primary} vs ref"] == "—" else f"{r[f'Δ{primary} vs ref']} {r['95% CI']}")
                      + " |" for n, r in rows.items()]
    out.append("## koniq10k at more image detail\n\nThe number is the image's soft tokens in training and prediction "
               "(280 is the default; 560 on seed 0 only, and only for the base and v3d runs). Δ is against the same start at 280 tokens on the same seed, "
               "which has the same 300 training rows.\n\n"
               f"| Run | soft NLL | {primary} | ρ(top p, agreement) | tie AUROC | Δ{primary} vs 280 [95% CI] |\n"
               "|---|---|---|---|---|---|\n" + "\n".join(table) + "\n")
    text = re.sub(r"\n{3,}", "\n\n", "\n".join(out))
    print(text)
    if a.out:
        a.out.write_text(text)


if __name__ == "__main__":
    main()
