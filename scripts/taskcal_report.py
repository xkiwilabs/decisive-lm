"""Task calibration of a bundle against P0 on two-sided and rating-kind development sets, with the raters' split-half
figures and a few-hundred-rating arm (results/taskcal_<bundle>.md; guide 10.6).

    uv run python scripts/taskcal_report.py --bundle general_v3d_e4b_r8_seed0 \
        --data data/processed/wiki_toxicity.jsonl data/processed/humicroedit.jsonl data/processed/csc_sarcasm.jsonl

Needs data/predictions/<bundle>__<set>.jsonl (scripts/predict_bundle.py) and teacher_<set>__gemma4_e4b.jsonl (P0).
For each set:
1. scripts/task_calibrate.py on all gold_calib rows, then scripts/eval_dataset.py on gold_test with the rows P0,
   P0+task, the bundle and bundle+task, P0+task the reference (1,000 paired item-level resamples, seed 0);
2. scripts/split_half.py on gold_test: how well one half of the raters predicts the other half's agreement;
3. the same task calibration fitted on a random 100 and 300 of the gold_calib rows, 5 draws each (seeds 0-4), with
   gold_test MAE and ρ(top p, agreement) averaged over the draws (range in brackets).
"""
import argparse
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
PRED = REPO / "data" / "predictions"
DRAWS, SIZES = 5, (100, 300)


def run(*args) -> str:
    return subprocess.run([sys.executable, *map(str, args)], cwd=REPO, check=True, capture_output=True,
                          text=True).stdout


def table_rows(markdown: str) -> dict[str, dict[str, str]]:
    """Method -> column -> cell, from eval_dataset.py's first table."""
    lines = [l for l in markdown.splitlines() if l.startswith("|")]
    head = [c.strip() for c in lines[0].strip("|").split("|")]
    return {cells[0]: dict(zip(head, cells)) for l in lines[2:] if (cells := [c.strip() for c in l.strip("|").split("|")])}


def eval_md(data, preds: dict[str, pathlib.Path], reference=None, n_boot=1000) -> str:
    args = [REPO / "scripts" / "eval_dataset.py", "--data", data, "--n-boot", n_boot,
            "--predictions", *[f"{k}={v}" for k, v in preds.items()]]
    if reference:
        args += ["--reference", reference]
    return run(*args)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", required=True)
    ap.add_argument("--data", type=pathlib.Path, nargs="+", required=True)
    ap.add_argument("--name", help="the bundle's name in the tables (default: the bundle)")
    ap.add_argument("--about", default="Development sets", help="what the sets are, the report's first words")
    ap.add_argument("--out", type=pathlib.Path)
    a = ap.parse_args()
    name = a.name or a.bundle
    out = [f"# Task calibration: {name} against P0\n",
           f"{a.about}, gold_test. Task calibration: a scale and an offset per level for each question, fitted "
           "on the set's gold_calib rows (`scripts/task_calibrate.py`, guide 10.6). Generated by "
           "`scripts/taskcal_report.py`.\n"]
    for data in a.data:
        stem = data.stem
        bundle, p0 = PRED / f"{a.bundle}__{stem}.jsonl", PRED / f"teacher_{stem}__gemma4_e4b.jsonl"
        run(REPO / "scripts" / "task_calibrate.py", "--data", data, "--predictions", p0, bundle)
        task = {p: p.with_name(p.stem + "_task.jsonl") for p in (p0, bundle)}
        md = eval_md(data, {"P0": p0, "P0+task": task[p0], name: bundle, f"{name}+task": task[bundle]},
                     reference="P0+task")
        out.append(f"## {stem}\n")
        out.append(md.split("\n", 1)[1].strip().replace("\n## ", "\n### ") + "\n")
        out.append("**Raters, half against half** (`scripts/split_half.py`): " + run(REPO / "scripts" / "split_half.py",
                                                                          "--data", data).strip() + "\n")
        primary = None
        sub = []
        for n in SIZES:
            for label, pred in (("P0+task", p0), (f"{name}+task", bundle)):
                main, rho = [], []
                for seed in range(DRAWS):
                    run(REPO / "scripts" / "task_calibrate.py", "--data", data, "--predictions", pred,
                        "--calib-rows", n, "--seed", seed)
                    f = pred.with_name(pred.stem + f"_task_n{n}_s{seed}.jsonl")
                    row = next(iter(table_rows(eval_md(data, {"x": f}, n_boot=1)).values()))
                    primary = next(h[:-len(" 95% CI")] for h in row if h.endswith(" 95% CI"))  # MAE or accuracy
                    main.append(float(row[primary]))
                    rho.append(float(row["ρ(top p, agreement)"]))
                sub.append(f"| {n} gold_calib rows | {label} "
                           f"| {sum(main) / DRAWS:.3f} [{min(main):.3f}, {max(main):.3f}] "
                           f"| {sum(rho) / DRAWS:+.3f} [{min(rho):+.3f}, {max(rho):+.3f}] |")
        sub = [f"| Fitted on | Method | {primary}, mean [range] | ρ(top p, agreement), mean [range] |",
               "|---|---|---|---|"] + sub
        out.append(f"**Fitted on fewer ratings**: {DRAWS} random draws (seeds 0-{DRAWS - 1}) of the gold_calib rows, "
                   "scored on all of gold_test.\n\n" + "\n".join(sub) + "\n")
    text = "\n".join(out)
    text = re.sub(r"\n{3,}", "\n\n", text)
    print(text)
    if a.out:
        a.out.write_text(text)


if __name__ == "__main__":
    main()
